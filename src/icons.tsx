export type IconName = keyof typeof ICON_PATHS;

const warned = new Set<string>();

/** 名前が辞書にあるか。サーバーから届いた文字列を絞り込むのに使う */
export function isIconName(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(ICON_PATHS, name);
}

/**
 * アイコン1つ。色は文字色（currentColor）をそのまま受け継ぐ。
 *
 * <p>選択中のボタンの白文字や、確認待ちの赤をアイコンにも効かせるため。
 * 名前が空なら何も描かない。知らない名前も何も描かない。
 */
export const Icon: React.FC<{
  name: string;
  size?: number;
  style?: React.CSSProperties;
}> = React.memo(({ name, size = 14, style }) => {
  if (name.length === 0) {
    return null;
  }
  if (!isIconName(name)) {
    if (!warned.has(name)) {
      warned.add(name);
      console.warn(`[icons] 知らないアイコン名: ${name}（icons.tsx に足すこと）`);
    }
    return null;
  }
  return (
    <svg
      aria-hidden="true"
      viewBox={VIEW_BOX}
      width={size}
      height={size}
      fill="currentColor"
      style={{ display: "block", flex: "0 0 auto", ...style }}
    >
      <path d={ICON_PATHS[name]} />
    </svg>
  );
});
Icon.displayName = "Icon";

